package repository

import (
	"context"
	"fmt"

	"github.com/jackc/pgx/v5/pgxpool"

	"github.com/rosha/mini-auth-system/auth-service/internal/model"
)

// UserRepository handles database operations for users.
type UserRepository struct {
	// pool manages reusable PostgreSQL connections.
	pool *pgxpool.Pool
}

// NewUserRepository creates a repository using the existing connection pool.
func NewUserRepository(pool *pgxpool.Pool) *UserRepository {
	return &UserRepository{
		pool: pool,
	}
}

// CreateUser inserts a new user into the users table.
func (r *UserRepository) CreateUser(
	ctx context.Context,
	phoneNumber string,
) (*model.User, error) {

	user := &model.User{}

	// RETURNING retrieves values generated by PostgreSQL.
	err := r.pool.QueryRow(
		ctx,
		`INSERT INTO users (phone_number)
		 VALUES ($1)
		 RETURNING id, phone_number, created_at, updated_at`,
		phoneNumber,
	).Scan(
		&user.ID,
		&user.PhoneNumber,
		&user.CreatedAt,
		&user.UpdatedAt,
	)

	if err != nil {
		return nil, fmt.Errorf("failed to create user: %w", err)
	}

	return user, nil
}

// GetUserByPhone retrieves a user using their phone number.
func (r *UserRepository) GetUserByPhone(
	ctx context.Context,
	phoneNumber string,
) (*model.User, error) {

	user := &model.User{}

	err := r.pool.QueryRow(
		ctx,
		`SELECT id, phone_number, created_at, updated_at
		 FROM users
		 WHERE phone_number = $1`,
		phoneNumber,
	).Scan(
		&user.ID,
		&user.PhoneNumber,
		&user.CreatedAt,
		&user.UpdatedAt,
	)

	if err != nil {
		return nil, fmt.Errorf("failed to retrieve user: %w", err)
	}

	return user, nil
}
